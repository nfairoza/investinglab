// Regenerate lib/market/constituents.ts from FMP's authoritative S&P 500 list.
//
// Usage:
//   MARKET_DATA_API_KEY=xxxx node scripts/refresh-constituents.mjs
//
// Tries FMP's sp500-constituents endpoint (probe-and-remember style: on a 4xx it
// reports the plan doesn't allow it and leaves the hand-authored fallback in
// place). On success it rewrites lib/market/constituents.ts with the current 503
// names grouped by GICS sector. Run quarterly.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const KEY = process.env.MARKET_DATA_API_KEY || process.env.FINANCIAL_DATA_API_KEY || "";
if (!KEY) { console.error("Set MARKET_DATA_API_KEY (or FINANCIAL_DATA_API_KEY)."); process.exit(1); }

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "lib", "market", "constituents.ts");

async function main() {
  const url = `https://financialmodelingprep.com/stable/sp500-constituents?apikey=${KEY}`;
  const r = await fetch(url, { cache: "no-store" });
  if (r.status >= 400 && r.status < 500) {
    console.error(`FMP sp500-constituents returned HTTP ${r.status} — likely plan-restricted.`);
    console.error("Leaving the hand-authored fallback in place. Upgrade the FMP plan or edit lib/market/constituents.ts by hand.");
    process.exit(2);
  }
  if (!r.ok) { console.error(`FMP HTTP ${r.status}`); process.exit(1); }
  const rows = await r.json();
  if (!Array.isArray(rows) || !rows.length) { console.error("Empty response."); process.exit(1); }

  // Group by sector, FMP labels. rows: { symbol, name, sector, ... }
  const bySector = {};
  for (const row of rows) {
    const symbol = String(row.symbol || "").toUpperCase();
    const name = String(row.name || symbol);
    const sector = String(row.sector || "Other");
    if (!symbol) continue;
    (bySector[sector] ??= []).push([symbol, name]);
  }

  const sectorBlocks = Object.entries(bySector)
    .map(([sector, list]) => {
      const items = list.map(([s, n]) => `    [${JSON.stringify(s)}, ${JSON.stringify(n)}],`).join("\n");
      return `  ${JSON.stringify(sector)}: [\n${items}\n  ],`;
    })
    .join("\n");

  const header = `// AUTO-GENERATED by scripts/refresh-constituents.mjs from FMP sp500-constituents.
// Do not edit by hand — re-run the script to refresh. Generated: ${new Date().toISOString().slice(0, 10)}.
`;
  // Reuse the same module shape as the hand-authored file so imports don't change.
  const body = `${header}
export interface Constituent { symbol: string; name: string; sector: string }

const BY_SECTOR: Record<string, Array<[string, string]>> = {
${sectorBlocks}
};

export const CONSTITUENTS: Constituent[] = (() => {
  const seen = new Set<string>();
  const out: Constituent[] = [];
  for (const [sector, rows] of Object.entries(BY_SECTOR)) {
    for (const [symbol, name] of rows) {
      const s = symbol.toUpperCase();
      if (seen.has(s)) continue;
      seen.add(s);
      out.push({ symbol: s, name, sector });
    }
  }
  return out;
})();

export function constituents(): Constituent[] { return CONSTITUENTS; }

export function bySector(): Record<string, string[]> {
  const m: Record<string, string[]> = {};
  for (const c of CONSTITUENTS) (m[c.sector] ??= []).push(c.symbol);
  return m;
}

export const SECTORS = Object.keys(BY_SECTOR);
`;

  await writeFile(OUT, body, "utf8");
  console.log(`Wrote ${rows.length} constituents across ${Object.keys(bySector).length} sectors → ${OUT}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
